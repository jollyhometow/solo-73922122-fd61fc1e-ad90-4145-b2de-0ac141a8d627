"""SQLite-backed storage for certified zone copies.

Design points enforced here:

* WAL journaling plus a busy timeout so the two uvicorn worker processes can
  share the database file without SQLITE_BUSY failures.
* The network transfer happens entirely outside this module; no write
  transaction (and thus no database write lock) is ever held while waiting on
  the network.  A backup only opens its single short write transaction once
  the full, authenticated zone data is in memory.
* Whole-version replacement is atomic from a reader's point of view: the new
  zone file is fsynced under a temporary name and renamed into place, and the
  metadata row is updated in the same transaction, so downloads can never mix
  records from two versions.
* Failed transfers never touch the database or the zone file, so the previous
  good version survives verification failures, truncation, timeouts and
  process interruption.
"""

from __future__ import annotations

import os
import sqlite3
import threading
from dataclasses import dataclass
from pathlib import Path

from .serial import SerialRelation, compare_serial

SCHEMA = """
CREATE TABLE IF NOT EXISTS zones (
    name          TEXT PRIMARY KEY,
    serial        INTEGER NOT NULL,
    record_count  INTEGER NOT NULL,
    message_count INTEGER NOT NULL,
    zone_file     TEXT NOT NULL,
    created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);
CREATE TABLE IF NOT EXISTS attempts (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    zone_name   TEXT NOT NULL,
    started_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    finished_at TEXT,
    ok          INTEGER NOT NULL DEFAULT 0,
    serial      INTEGER,
    record_count INTEGER,
    reason      TEXT
);
"""


class CommitRejected(Exception):
    """Raised when RFC 1982 ordering rules reject an incoming version."""

    def __init__(self, reason: str, relation: SerialRelation):
        super().__init__(reason)
        self.reason = reason
        self.relation = relation


@dataclass(frozen=True)
class StoredZone:
    name: str
    serial: int
    record_count: int
    message_count: int
    zone_file: str
    created_at: str
    updated_at: str


@dataclass(frozen=True)
class CommitOutcome:
    status: str  # saved | unchanged | rejected
    reason: str
    stored: StoredZone | None


def render_zone_file(origin: str, rrs: list[tuple[str, int, str, str]]) -> str:
    """Render validated records into a standard RFC 1035 master file."""
    lines = [
        f"; Authenticated AXFR backup of {origin}",
        "; Generated by dns-zone-backup; do not edit by hand.",
        "$ORIGIN .",
    ]
    for name, ttl, rdtype, rdata in rrs:
        lines.append(f"{name}\t{ttl}\tIN\t{rdtype}\t{rdata}")
    lines.append("")
    return "\n".join(lines)


class Storage:
    def __init__(self, db_path: str | os.PathLike[str], files_dir: str | os.PathLike[str]):
        self.db_path = Path(db_path)
        self.files_dir = Path(files_dir)
        self.files_dir.mkdir(parents=True, exist_ok=True)
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        self._init_lock = threading.Lock()
        self._init_conn()

    def _connect(self) -> sqlite3.Connection:
        conn = sqlite3.connect(
            str(self.db_path), timeout=10, isolation_level=None
        )
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA journal_mode=WAL")
        conn.execute("PRAGMA synchronous=FULL")
        conn.execute("PRAGMA busy_timeout=10000")
        conn.execute("PRAGMA foreign_keys=ON")
        return conn

    def _init_conn(self) -> None:
        with self._init_lock:
            conn = self._connect()
            try:
                conn.executescript(SCHEMA)
            finally:
                conn.close()

    # ---- reads -----------------------------------------------------------

    def get_zone(self, name: str) -> StoredZone | None:
        conn = self._connect()
        try:
            row = conn.execute(
                "SELECT * FROM zones WHERE name = ?", (name,)
            ).fetchone()
            return self._row_to_zone(row) if row else None
        finally:
            conn.close()

    def list_zones(self) -> list[StoredZone]:
        conn = self._connect()
        try:
            rows = conn.execute(
                "SELECT * FROM zones ORDER BY name"
            ).fetchall()
            return [self._row_to_zone(row) for row in rows]
        finally:
            conn.close()

    def read_zone_file(self, zone: StoredZone) -> str:
        # Reading from the path recorded in the row guarantees the contents
        # match the metadata version even while a replacement is being renamed.
        return Path(zone.zone_file).read_text(encoding="utf-8")

    def recent_attempts(self, limit: int = 10) -> list[sqlite3.Row]:
        conn = self._connect()
        try:
            return list(
                conn.execute(
                    "SELECT * FROM attempts ORDER BY id DESC LIMIT ?", (limit,)
                ).fetchall()
            )
        finally:
            conn.close()

    def record_attempt_start(self, zone_name: str) -> int:
        conn = self._connect()
        try:
            cur = conn.execute(
                "INSERT INTO attempts (zone_name) VALUES (?)", (zone_name,)
            )
            return int(cur.lastrowid)
        finally:
            conn.close()

    def record_attempt_finish(
        self,
        attempt_id: int,
        ok: bool,
        serial: int | None,
        record_count: int | None,
        reason: str | None,
    ) -> None:
        conn = self._connect()
        try:
            conn.execute(
                "UPDATE attempts SET finished_at = "
                "strftime('%Y-%m-%dT%H:%M:%fZ','now'), ok = ?, serial = ?, "
                "record_count = ?, reason = ? WHERE id = ?",
                (1 if ok else 0, serial, record_count, reason, attempt_id),
            )
        finally:
            conn.close()

    # ---- the only write path used by a successful backup ------------------

    def commit_backup(
        self,
        origin: str,
        serial: int,
        rrs: list[tuple[str, int, str, str]],
        message_count: int,
    ) -> CommitOutcome:
        """Atomically save a fully authenticated transfer.

        RFC 1982 ordering against the latest stored serial is decided inside
        this single short transaction.  No network activity happens here.
        """
        conn = self._connect()
        try:
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute(
                "SELECT * FROM zones WHERE name = ?", (origin,)
            ).fetchone()
            stored = self._row_to_zone(row) if row else None

            if stored is not None:
                relation = compare_serial(serial, stored.serial)
                if relation is SerialRelation.EQUAL:
                    conn.rollback()
                    return CommitOutcome(
                        "unchanged",
                        f"序列号 {serial} 与已存版本相同，未做改动",
                        stored,
                    )
                if relation is SerialRelation.AMBIGUOUS:
                    conn.rollback()
                    raise CommitRejected(
                        f"新序列号 {serial} 与已存序列号 {stored.serial} 之差为 2^31，"
                        "RFC 1982 无法确定先后，拒绝写入并保留旧版",
                        relation,
                    )
                if relation is SerialRelation.OLDER:
                    conn.rollback()
                    raise CommitRejected(
                        f"新序列号 {serial} 按 RFC 1982 早于已存序列号 "
                        f"{stored.serial}，拒绝用旧版覆盖，保留已存新版",
                        relation,
                    )

            # Newer, or no copy exists yet: full-version replacement.
            zone_text = render_zone_file(origin, rrs)
            final_path = self.files_dir / f"{_safe_filename(origin)}.zone"
            tmp_path = final_path.with_suffix(".zone.tmp")
            with open(tmp_path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(zone_text)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp_path, final_path)

            if stored is None:
                conn.execute(
                    "INSERT INTO zones (name, serial, record_count, "
                    "message_count, zone_file) VALUES (?, ?, ?, ?, ?)",
                    (origin, serial, len(rrs), message_count, str(final_path)),
                )
            else:
                conn.execute(
                    "UPDATE zones SET serial = ?, record_count = ?, "
                    "message_count = ?, zone_file = ?, updated_at = "
                    "strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE name = ?",
                    (
                        serial,
                        len(rrs),
                        message_count,
                        str(final_path),
                        origin,
                    ),
                )
            conn.commit()
            refreshed = self.get_zone(origin)
            reason = (
                "此前无副本，已直接保存首版"
                if stored is None
                else f"序列号 {serial} 较新，已整版替换旧版"
            )
            return CommitOutcome("saved", reason, refreshed)
        except Exception:
            try:
                conn.rollback()
            except sqlite3.Error:
                pass
            raise
        finally:
            conn.close()

    @staticmethod
    def _row_to_zone(row: sqlite3.Row) -> StoredZone:
        return StoredZone(
            name=row["name"],
            serial=int(row["serial"]),
            record_count=int(row["record_count"]),
            message_count=int(row["message_count"]),
            zone_file=row["zone_file"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
        )


def _safe_filename(origin: str) -> str:
    cleaned = origin.rstrip(".").replace(".", "_")
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in cleaned)
